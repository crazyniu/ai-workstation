#!/usr/bin/env python3
"""Add credential-free MCP defaults to a home directory, preserving user settings."""
import argparse
import json
import os
from pathlib import Path
import tempfile
import tomllib


def servers():
    def local(name, args=()):
        return {"command": "/usr/local/bin/workstation-mcp", "args": [name, *args]}
    return {
        "context7": local("context7"),
        "playwright": local("playwright", ["--executable-path", "/usr/bin/google-chrome-stable", "--headless", "--isolated", "--sandbox"]),
        "chrome-devtools": local("chrome-devtools", ["--executablePath", "/usr/bin/google-chrome-stable", "--headless", "--isolated", "--no-usage-statistics", "--no-performance-crux"]),
        "github": {"url": "https://api.githubcopilot.com/mcp/"},
    }


def atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(text)
    try:
        temporary.chmod(0o600)
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def retired_servers(servers):
    """Identify game integrations generated by earlier workstation images."""
    return [name for name, server in servers.items()
            if name in ('unity', 'godot') and
            (server.get('command') == '/usr/local/bin/unity-mcp' or
             (server.get('command') == '/usr/local/bin/workstation-mcp' and
              server.get('args', [])[:1] == [name]))]


def configure(home, only=None):
    defaults = servers()
    if only:
        defaults = {name: defaults[name] for name in only}
    codex = home / ".codex/config.toml"
    original = codex.read_text() if codex.exists() else ""
    parsed = tomllib.loads(original)
    retired = retired_servers(parsed.get("mcp_servers", {}))
    if retired:
        import tomlkit
        document = tomlkit.parse(original)
        for name in retired:
            del document["mcp_servers"][name]
        original = tomlkit.dumps(document)
    additions = []
    for name, server in defaults.items():
        if name in parsed.get("mcp_servers", {}):
            continue
        additions.append(f"[mcp_servers.{json.dumps(name)}]")
        for key, value in server.items():
            additions.append(f"{key} = {json.dumps(value)}")
        additions.append("startup_timeout_sec = 60")
        if name == "github":
            additions.append('bearer_token_env_var = "GITHUB_PAT_TOKEN"')
        additions.append("")
    if additions:
        original = original.rstrip() + "\n\n# Workstation MCP defaults; GitHub requires your own token.\n" + "\n".join(additions)
    if retired or additions:
        tomllib.loads(original)
        atomic_write(codex, original)
    claude = home / ".claude.json"
    config = json.loads(claude.read_text()) if claude.exists() else {}
    configured = config.setdefault("mcpServers", {})
    retired = retired_servers(configured)
    for name in retired:
        del configured[name]
    changed = bool(retired)
    for name, server in defaults.items():
        if name in configured:
            continue
        server = dict(server)
        server["type"] = "http" if name == "github" else "stdio"
        configured[name] = server
        changed = True
    if changed:
        atomic_write(claude, json.dumps(config, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--home", type=Path, default=Path.home())
    parser.add_argument("--only", nargs="+", choices=servers(), help="Add only these servers to an existing installation")
    args = parser.parse_args()
    configure(args.home, args.only)
